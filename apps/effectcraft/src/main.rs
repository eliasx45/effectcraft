/// Both native JSON projects and Save a Copy As XML projects are openable on launch.
/// Keep this classification shared by project opening and the subsequent media-import pass.
fn is_project_file(path: &str) -> bool {
    std::path::Path::new(path)
        .extension()
        .and_then(|ext| ext.to_str())
        .is_some_and(|ext| ext.eq_ignore_ascii_case("ecproj") || ext.eq_ignore_ascii_case("ecprojx"))
}

/// winit 0.30 cannot deliver native Wayland file drops. XWayland can.
#[cfg(target_os = "linux")]
fn wayland_drop_notice(wayland_display: Option<&std::ffi::OsStr>, backend: Option<&std::ffi::OsStr>) -> Option<&'static str> {
    (wayland_display.is_some_and(|v| !v.is_empty()) && backend != Some(std::ffi::OsStr::new("x11")))
        .then_some("Native Wayland file drops are unavailable. Use File ▸ Import ▸ File… or run via XWayland (see README, Linux).")
}

/// Whether the window will be on an X server (winit prefers Wayland when both are there).
#[cfg(target_os = "linux")]
fn on_x11(display: Option<&std::ffi::OsStr>, wayland_display: Option<&std::ffi::OsStr>, backend: Option<&std::ffi::OsStr>) -> bool {
    let set = |v: Option<&std::ffi::OsStr>| v.is_some_and(|v| !v.is_empty());
    set(display) && (!set(wayland_display) || backend == Some(std::ffi::OsStr::new("x11")))
}

/// An X server without DRI3 (Xvfb, a cloud desktop streamed by Selkies or VNC): the Vulkan
/// driver presents there by copying the window through the X server (`PutImage`), which holds
/// up a queue the compositor shares. Uncached playback on an RTX 3090 behind Selkies ran at
/// 14–17 fps with zero-copy display and 30 fps without, so it starts off there.
#[cfg(target_os = "linux")]
fn x_server_without_dri3() -> bool {
    use x11rb::connection::RequestConnection;
    let env = |k: &str| std::env::var_os(k);
    if !on_x11(env("DISPLAY").as_deref(), env("WAYLAND_DISPLAY").as_deref(), env("WINIT_UNIX_BACKEND").as_deref()) {
        return false;
    }
    let Ok((conn, _)) = x11rb::connect(None) else { return false };
    matches!(conn.extension_information("DRI3"), Ok(None))
}

/// The command line.
#[derive(Debug, Default, PartialEq)]
struct Args {
    control_port: Option<u16>,
    files: Vec<String>,
    /// Open the demo project when no project is given (`--demo`).
    demo: bool,
    /// Show or skip the Home screen (`--home`), else the Startup preference decides.
    home: Option<bool>,
}

/// Parse the arguments after the program name; `Ok(None)` for `--version`. `env_port` is
/// `EFFECTCRAFT_CONTROL_PORT`, used when `--control` isn't given. An unknown option or a bad port
/// is an error, so it is neither imported as a file nor dropped; after `--` every argument is a file.
fn parse_args(args: impl IntoIterator<Item = String>, env_port: Result<String, std::env::VarError>) -> Result<Option<Args>, String> {
    let mut out = Args::default();
    let mut args = args.into_iter();
    let mut options = true;
    while let Some(a) = args.next() {
        if !options {
            out.files.push(a);
            continue;
        }
        match a.as_str() {
            "--" => options = false,
            "--control" => out.control_port = Some(control_port("--control", args.next().as_deref())?),
            "--demo" => out.demo = true,
            "--empty" => out.demo = false,
            "--home" => out.home = Some(true),
            "--version" => return Ok(None),
            _ => match a.strip_prefix("--control=") {
                Some(v) => out.control_port = Some(control_port("--control", Some(v))?),
                // macOS LaunchServices may pass a process serial number (`-psn_0_1234`), notably on
                // the first launch of a downloaded app; it is not an option of ours.
                None if a.starts_with("-psn_") => {}
                None if a.starts_with('-') && a != "-" => return Err(format!("unknown option `{a}`")),
                None => out.files.push(a),
            },
        }
    }
    if out.control_port.is_none() {
        out.control_port = match env_port {
            Ok(v) if v.is_empty() => None,
            Ok(v) => Some(control_port("EFFECTCRAFT_CONTROL_PORT", Some(&v))?),
            Err(std::env::VarError::NotPresent) => None,
            Err(std::env::VarError::NotUnicode(v)) => Some(control_port("EFFECTCRAFT_CONTROL_PORT", Some(&v.to_string_lossy()))?),
        };
    }
    Ok(Some(out))
}

/// A control-channel port from 1 to 65535 (0 would listen on a port nobody is told); `name` is
/// the flag or variable it came from.
fn control_port(name: &str, value: Option<&str>) -> Result<u16, String> {
    let need = format!("{name} needs a port number from 1 to 65535");
    match value {
        None => Err(need),
        Some(v) => v.parse().ok().filter(|&p| p != 0).ok_or(format!("{need}, not `{v}`")),
    }
}

fn main() -> eframe::Result {
    // First, so the panic hook and every start-up warning are recorded. Records go to stderr
    // and the session log; Help ▸ Enable Logging writes through this logger too, and warnings
    // feed the compatibility report.
    effectcraft_engine::logging::install();
    effectcraft_engine::logging::install_panic_hook();
    let Args { control_port, files, demo, home } = match parse_args(std::env::args().skip(1), std::env::var("EFFECTCRAFT_CONTROL_PORT")) {
        Ok(Some(args)) => args,
        Ok(None) => {
            println!("effectcraft {}", env!("CARGO_PKG_VERSION"));
            return Ok(());
        }
        // Before the session log, preferences and the window: nothing has started yet.
        Err(e) => {
            eprintln!("effectcraft: {e}");
            std::process::exit(1);
        }
    };
    // Hardware ProRes decoding for previews; exports keep their exact decoder.
    log::info!("hardware ProRes decoding: {:?}", effectcraft_platform::register());
    // Cache Frames When Idle renders at background priority (macOS utility QoS), after the UI,
    // playback and other apps.
    effectcraft_ui_egui::frames::set_idle_thread_start(|| {
        effectcraft_platform::background_thread();
    });
    // The session log lives in the settings folder (`Logs/effectcraft.log`, the previous two runs
    // kept): a launch from the Dock or a menu has no terminal. Opened after the arguments, so
    // `--version` leaves no file behind; records logged until now are written to it first.
    if let Some(dir) = effectcraft_host::config_dir() {
        match effectcraft_engine::logging::attach_session_log(&effectcraft_engine::logging::log_dir(Some(&dir))) {
            Ok(path) => log::info!("effectcraft {}, log file {}", env!("CARGO_PKG_VERSION"), path.display()),
            Err(e) => log::warn!("no log file: {e}"),
        }
    }
    // The font menus list the installed fonts: read their names while the window opens.
    effectcraft_engine::text::fonts::scan_system_in_background();
    // In the host list (which project is open where; the control port is added once it listens).
    if let Some(dir) = effectcraft_host::config_dir() {
        effectcraft_engine::hosts::announce(&dir, "app", None);
    }
    // Wayland shows the window's icon from its desktop entry: an AppImage brings its own.
    #[cfg(target_os = "linux")]
    appimage::integrate_from_env(ICON_PNG);
    // Settings ▸ Startup & Repair ▸ Window Graphics, switched to OpenGL when the last launch
    // stopped as its window opened (a crashing graphics driver, #243).
    let mut launch = launch_guard::Launch::begin(effectcraft_host::config_dir().as_deref(), std::env::var_os("WGPU_BACKEND").is_some());
    let on_gl = launch.backends == Some(eframe::wgpu::Backends::GL);
    let notice = launch.notice.take();
    // RT10e: the GPU compositor shares the window's device (viewer frames without a copy), with
    // the window's events gated (`surface_gate`). `EFFECTCRAFT_ZERO_COPY=0`: as before.
    // Off by default on an X server without DRI3 (see `x_server_without_dri3`).
    #[cfg(target_os = "linux")]
    let software_x = effectcraft_ui_egui::zero_copy::env_choice().is_none() && x_server_without_dri3();
    #[cfg(not(target_os = "linux"))]
    let software_x = false;
    if software_x {
        log::info!(
            "zero-copy display off: the X server has no DRI3, so the window presents through it ({}=1 turns it on)",
            effectcraft_ui_egui::zero_copy::ENV
        );
    }
    let gate = (effectcraft_ui_egui::zero_copy::env_choice() != Some(false) && !software_x && !on_gl).then(surface_gate::Gate::new);
    let app_gate = gate.clone();
    let options = eframe::NativeOptions {
        viewport: egui::ViewportBuilder::default()
            .with_title("EffectCraft")
            .with_inner_size(window::DEFAULT_SIZE)
            .with_min_inner_size(window::MIN_SIZE)
            .with_drag_and_drop(true)
            // Started for an agent (`--control`): open without taking the user's keyboard focus.
            .with_active(control_port.is_none())
            .with_icon(app_icon())
            // Wayland matches the window to `ai.storyteller.effectcraft.desktop` by this ID.
            .with_app_id(appimage::APP_ID),
        event_loop_builder: agent_event_loop(control_port.is_some()),
        wgpu_options: wgpu_options(launch.backends, gate.clone()),
        ..Default::default()
    };
    // Start-up milestones go to stderr and the session log, so a window that never appears
    // shows how far start-up got (#234).
    log::info!("effectcraft {}: opening the window", env!("CARGO_PKG_VERSION"));
    // Registered before the event loop starts, so it catches the Finder event that launched us as
    // well as later ones. Lives until the event loop returns; the app creator only borrows it.
    #[cfg(target_os = "macos")]
    let apple_events = apple_events::AppleEvents::install();
    #[cfg(target_os = "macos")]
    let apple_events = &apple_events;
    let creator: eframe::AppCreator<'_> = Box::new(move |cc| {
        match &cc.wgpu_render_state {
            Some(rs) => log::info!("graphics: {:?}", rs.adapter.get_info()),
            None => log::info!("graphics: no wgpu device"),
        }
        // This executable owns the shared device's handlers. Install them before
        // EffectCraft's compositor pipelines are built, without changing handlers from
        // inside Gpu::new. eframe has already constructed its presentation renderer here.
        let gpu_failures = effectcraft_ui_egui::gpu_failure::GpuFailureBridge::new(&cc.egui_ctx);
        if let Some(rs) = &cc.wgpu_render_state {
            let errors = gpu_failures.clone();
            rs.device.on_uncaptured_error(std::sync::Arc::new(move |error| {
                let message = format!("uncaptured GPU error: {error}");
                if errors.report(&message, false) {
                    log::error!("{message}");
                }
            }));
            let lost = gpu_failures.clone();
            rs.device.set_device_lost_callback(move |reason, message| {
                lost.report(&format!("GPU device lost ({reason:?}): {message}"), true);
            });
        }
        let mut session = effectcraft_host::session();
        // Lazy open and non-blocking auto-save: footage is checked and auto-saves are
        // written on background threads (M13.14).
        session.check_footage_on_open = true;
        session.autosave.background = true;
        // Settings, shortcut presets and the crash-recovery sentinel live in the platform
        // config directory. Agent-driven runs (`--control`) skip crash recovery.
        if let Some(dir) = effectcraft_host::config_dir() {
            // WebAssembly effect plug-ins in <config>/Plug-ins load before the menus are built.
            let plugins = dir.join("Plug-ins");
            if plugins.is_dir() {
                let _ = session.execute("effect.plugins.load", json!({"folder": plugins.to_string_lossy()}));
            }
            session.config = Some(std::sync::Arc::new(effectcraft_engine::config::DirConfig::new(dir)));
        }
        session.load_settings();
        // Fit the window to its monitor, or put it back where it was (still hidden).
        let saved_window = session.config.as_deref().and_then(window::load);
        let opened = cc.winit_window().map(|w| window::restore(w, saved_window));
        // Settings ▸ Scripting & Expressions ▸ Let Agents Control EffectCraft: the control
        // channel on every launch, without `--control`'s agent-launch behaviour.
        let agent = &session.prefs.scripting;
        let listen_port = control_port.or_else(|| agent.agent_control.then(|| u16::try_from(agent.agent_control_port).ok()).flatten());
        let recovery = if control_port.is_none() { session.begin_recovery() } else { None };
        let project = files.iter().find(|f| is_project_file(f)).cloned();
        if let Some(p) = project {
            if let Err(e) = session.execute("file.open", json!({"path": p})) {
                log::warn!("{p}: {e}");
            }
        } else if demo {
            let _ = session.execute("file.openDemoProject", json!({}));
        }
        let media: Vec<String> = files.iter().filter(|f| !is_project_file(f)).cloned().collect();
        if !media.is_empty()
            && let Err(e) = session.execute("file.import", json!({"paths": media}))
        {
            log::warn!("import: {e}");
        }
        let show_home = home.unwrap_or(session.prefs.startup.show_home_on_launch && files.is_empty() && control_port.is_none());
        // The ScriptUI panels open when the app last quit open again (a failing one is
        // reported in a toast and forgotten).
        let _ = session.execute("window.restoreScriptPanels", json!({}));
        let mut app = EffectcraftApp::new(session);
        app.set_gpu_failure_bridge(gpu_failures);
        if on_gl {
            app.keep_compositor_on_window_adapter();
        }
        if let Some(gate) = &app_gate {
            app.share_display_device(Some(gate.light.clone()));
        }
        app.ui.start_screen = show_home;
        if let Some(n) = notice {
            app.ui.status = n;
        }
        if let Some(r) = recovery {
            app.offer_recovery(r);
        }
        #[cfg(target_os = "linux")]
        if let Some(note) = wayland_drop_notice(std::env::var_os("WAYLAND_DISPLAY").as_deref(), std::env::var_os("WINIT_UNIX_BACKEND").as_deref())
            && app.ui.status.is_empty()
        {
            app.ui.status = note.into();
        }
        app.hooks.pick_files = Some(Box::new(|exts: &[&str]| {
            rfd::FileDialog::new().add_filter("Media", exts).pick_files().unwrap_or_default().into_iter().map(|p| p.to_string_lossy().to_string()).collect()
        }));
        app.hooks.pick_save = Some(Box::new(|name: &str| {
            rfd::FileDialog::new().add_filter("EffectCraft Project", &["ecproj"]).set_file_name(name).save_file().map(|p| p.to_string_lossy().to_string())
        }));
        // The window closes after a lost graphics device (#591); say why, unless an agent drives
        // the app through the control channel.
        if control_port.is_none() {
            app.hooks.device_lost = Some(Box::new(|saved: Option<Result<String, String>>| {
                let saved = match saved {
                    Some(Ok(path)) => format!("\n\nYour unsaved changes were saved to:\n{path}\n\nReopen EffectCraft to recover them."),
                    Some(Err(e)) => format!("\n\nYour unsaved changes could not be saved ({e})."),
                    None => String::new(),
                };
                rfd::MessageDialog::new()
                    .set_level(rfd::MessageLevel::Error)
                    .set_title("EffectCraft: graphics device lost")
                    .set_description(format!("The graphics driver stopped responding, so EffectCraft has to close.{saved}"))
                    .show();
            }));
        }
        app.hooks.pick_open_project = Some(Box::new(|| {
            rfd::FileDialog::new().add_filter("EffectCraft Project", &["ecproj", "ecprojx"]).pick_file().map(|p| p.to_string_lossy().to_string())
        }));
        app.hooks.system_theme = appearance::service();
        app.hooks.audio_device = Some(Box::new(audio_out::open));
        app.hooks.audio_devices = Some(Box::new(audio_out::devices));
        app.hooks.pick_folder = Some(Box::new(|| rfd::FileDialog::new().pick_folder().map(|p| p.to_string_lossy().to_string())));
        app.hooks.pick_save_file = Some(Box::new(|name: &str, ext: &str| {
            // A default with a folder that exists opens the dialog there.
            let path = std::path::Path::new(name);
            // (No filter for a name without an extension, such as a folder to create.)
            let mut d = if ext.is_empty() { rfd::FileDialog::new() } else { rfd::FileDialog::new().add_filter(ext, &[ext]) };
            if let Some(dir) = path.parent().filter(|d| d.is_dir()) {
                d = d.set_directory(dir);
            }
            let file = path.file_name().map(|n| n.to_string_lossy().to_string()).unwrap_or_default();
            d.set_file_name(file).save_file().map(|p| p.to_string_lossy().to_string())
        }));
        #[cfg(target_os = "macos")]
        {
            // The commands' file dialogs open as sheets instead of nested modal loops (#511).
            let ctx = cc.egui_ctx.clone();
            app.hooks.file_dialog_async = Some(Box::new(move |dialog, done| sheet_dialogs::show(dialog, done, ctx.clone())));
            app.hooks.app_action = Some(Box::new(native_menu::app_action));
            app.hooks.clipboard_text = Some(Box::new(native_menu::clipboard_text));
        }
        // The control channel and the Figma bridge feed the same request queue.
        // Not for agent launches (`--control`), which would take the person's port 7789,
        // unless EFFECTCRAFT_FIGMA_BRIDGE_PORT asks for it.
        let figma_bridge = app.session.prefs.scripting.figma_bridge && (control_port.is_none() || std::env::var_os("EFFECTCRAFT_FIGMA_BRIDGE_PORT").is_some());
        if listen_port.is_some() || figma_bridge {
            let (tx, rx) = std::sync::mpsc::channel();
            if let Some(port) = listen_port {
                match control_server::start(port, cc.egui_ctx.clone(), awake_while_busy(tx.clone(), &cc.egui_ctx)) {
                    Ok(started) => {
                        eprintln!("effectcraft: control server listening on 127.0.0.1:{}", started.port);
                        // In the host list, joinable on this port (`hosts.list`).
                        if let Some(dir) = effectcraft_host::config_dir() {
                            effectcraft_engine::hosts::announce(&dir, "app", Some(started.port));
                        }
                        app = app.with_control_events(started.events);
                    }
                    // Another app (often a second EffectCraft) holds the port: say so in the
                    // window, or an agent's `--bridge` silently drives the other app.
                    Err(e) => {
                        eprintln!("effectcraft: {e}");
                        log::error!("{e}");
                        app.ui.status = e;
                    }
                }
            }
            if figma_bridge {
                figma_host::start(tx, cc.egui_ctx.clone());
            }
            app = app.with_control(rx);
        }
        log::info!("app created; the window shows after its first frame");
        Ok(Box::new(Desktop {
            #[cfg(target_os = "macos")]
            menu: native_menu::NativeBar::new(&cc.egui_ctx),
            #[cfg(target_os = "macos")]
            apple_events: apple_events.connect(&cc.egui_ctx),
            app,
            window: window::Tracker::new(opened, saved_window, control_port.is_none()),
            launch,
            drawn: false,
        }))
    });
    let result = match gate {
        Some(gate) => surface_gate::run("EffectCraft", options, creator, gate),
        None => eframe::run_native("EffectCraft", options, creator),
    };
    match &result {
        Ok(()) => log::info!("the window closed"),
        Err(e) => {
            if on_gl {
                launch_guard::opengl_failed(effectcraft_host::config_dir().as_deref());
            } else {
                launch_guard::window_failed(effectcraft_host::config_dir().as_deref());
            }
            startup_failed(e, !on_gl && cfg!(not(target_os = "macos")));
        }
    }
    effectcraft_engine::hosts::withdraw();
    result
}

/// The window's wgpu device asks for the adapter's own limits (textures up to 16384 px)
/// instead of eframe's fixed set: an older GPU that can't meet those (Intel HD Graphics 5500,
/// #198) still opens the app, and the compositor then checks what it needs and falls back to
/// the CPU when the device can't run it. `backends`: Window Graphics' choice, when it makes one.
fn wgpu_options(backends: Option<eframe::wgpu::Backends>, gate: Option<std::sync::Arc<surface_gate::Gate>>) -> eframe::WgpuConfiguration {
    use eframe::egui_wgpu::WgpuSetup;
    let mut config = eframe::WgpuConfiguration::default();
    if let Some(gate) = gate {
        // Frames that come back outdated or lost are reconfigured next: hold the compositor.
        let default = config.on_surface_status.clone();
        config.on_surface_status = std::sync::Arc::new(move |status| gate.surface_status(status, default(status)));
    }
    if let WgpuSetup::CreateNew(setup) = &mut config.wgpu_setup {
        if let Some(b) = backends {
            setup.instance_descriptor.backends = b;
        }
        // Nothing draws or dispatches indirectly, so wgpu's check of indirect arguments only costs
        // a compute shader when the device is created, one that Metal can't compile on an Intel
        // Iris Pro: the device is lost and the window never opens.
        // `WGPU_VALIDATION_INDIRECT_CALL=1` turns the check back on.
        setup.instance_descriptor.flags = setup.instance_descriptor.flags.difference(eframe::wgpu::InstanceFlags::VALIDATION_INDIRECT_CALL).with_env();
        // CR1: on Vulkan and Direct3D 12 a texture past 90 % of the video memory budget fails
        // with an out-of-memory error the frame's error scope catches (the GPU preview backs off)
        // instead of overcommitting until the device is lost (`effectcraft_gpu::vram`).
        setup.instance_descriptor.memory_budget_thresholds = eframe::wgpu::MemoryBudgetThresholds { for_resource_creation: Some(90), for_device_loss: None };
        setup.device_descriptor = std::sync::Arc::new(|adapter| eframe::wgpu::DeviceDescriptor {
            label: Some("EffectCraft device"),
            required_limits: device_limits(adapter.limits()),
            ..Default::default()
        });
    }
    config
}

/// The limits to request from an adapter that offers `adapter`: all of them, with textures
/// capped at 16384 px like the headless renderer's device.
fn device_limits(adapter: eframe::wgpu::Limits) -> eframe::wgpu::Limits {
    eframe::wgpu::Limits { max_texture_dimension_2d: adapter.max_texture_dimension_2d.min(16384), ..adapter }
}

/// The window couldn't open (no usable graphics adapter or device): say so instead of quitting
/// silently, since release builds on Windows have no console. `gl_next`: the launch guard has
/// the next launch try OpenGL.
fn startup_failed(e: &eframe::Error, gl_next: bool) {
    let next = if gl_next { "The next launch will try OpenGL instead. " } else { "" };
    let message = format!(
        "EffectCraft couldn't start its window: {e}\n\n{next}Updating the graphics driver often helps. If it keeps happening, please report it at https://github.com/storytold/effectcraft/issues with this message."
    );
    // Standard error and the session log; standard error alone when RUST_LOG turned errors off.
    if log::log_enabled!(log::Level::Error) {
        log::error!("{message}");
    } else {
        eprintln!("effectcraft: {message}");
    }
    let _ = rfd::MessageDialog::new()
        .set_level(rfd::MessageLevel::Error)
        .set_title("EffectCraft")
        .set_description(message)
        .set_buttons(rfd::MessageButtons::Ok)
        .show();
}

/// The desktop app: the egui app plus, on macOS, the system menu bar.
struct Desktop {
    app: EffectcraftApp,
    #[cfg(target_os = "macos")]
    menu: native_menu::NativeBar,
    /// Documents opened from Finder, the Dock or `open` (macOS).
    #[cfg(target_os = "macos")]
    apple_events: apple_events::Opened,
    /// The window's size and position, saved for the next launch.
    window: window::Tracker,
    launch: launch_guard::Launch,
    /// The first frame was drawn (logged once).
    drawn: bool,
}

impl eframe::App for Desktop {
    fn logic(&mut self, ctx: &egui::Context, frame: &mut eframe::Frame) {
        #[cfg(target_os = "macos")]
        self.menu.update(&mut self.app, ctx);
        self.app.logic(ctx, frame);
    }

    fn ui(&mut self, ui: &mut egui::Ui, frame: &mut eframe::Frame) {
        self.app.ui(ui, frame);
        self.window.frame(ui.ctx(), self.app.session.config.as_deref());
        if !self.drawn {
            self.drawn = true;
            log::info!("first frame drawn");
        }
        // The launch guard's marker goes once the window has kept drawing for a few seconds: a
        // driver may still crash as the window is shown and its surface re-created.
        if let Some(left) = self.launch.frame_drawn() {
            ui.ctx().request_repaint_after(left);
        }
    }

    fn on_exit(&mut self) {
        self.launch.exited();
        self.window.save(self.app.session.config.as_deref());
        self.app.on_exit();
    }

    fn raw_input_hook(&mut self, ctx: &egui::Context, raw_input: &mut egui::RawInput) {
        #[cfg(target_os = "macos")]
        self.apple_events.feed(self.app.is_ready(), ctx, raw_input);
        self.app.raw_input_hook(ctx, raw_input);
    }
}

/// Driven by an agent (`--control`): don't activate the app on launch, so the user's keyboard
/// focus stays where it is (macOS; winit activates ignoring other apps by default).
fn agent_event_loop(agent: bool) -> Option<eframe::EventLoopBuilderHook> {
    #[cfg(target_os = "macos")]
    if agent {
        return Some(Box::new(|b| {
            use winit::platform::macos::EventLoopBuilderExtMacOS;
            b.with_activate_ignoring_other_apps(false);
        }));
    }
    let _ = agent;
    None
}

/// Agents drive the app while its window is covered or on another Space. macOS App Nap would
/// throttle the event loop then, stalling the control channel; a latency-critical activity is
/// held while control requests are in flight (and [`AWAKE_LINGER`] after the last reply, so a
/// script's back-to-back requests share one). Between them the app naps like any other, and the
/// server still listens: a new request wakes it. Elsewhere requests go straight to the app.
fn awake_while_busy(to_app: Sender<ControlRequest>, ctx: &egui::Context) -> Sender<ControlRequest> {
    #[cfg(target_os = "macos")]
    {
        let hold = || {
            use objc2_foundation::{NSActivityOptions, NSProcessInfo, NSString};
            // The activity ends when its token is released (dropped). The pool keeps an
            // autoreleased token from outliving the drop on this pool-less thread.
            objc2::rc::autoreleasepool(|_| {
                let reason = NSString::from_str("EffectCraft control channel");
                let opts = NSActivityOptions::UserInitiatedAllowingIdleSystemSleep | NSActivityOptions::LatencyCritical;
                Some(NSProcessInfo::processInfo().beginActivityWithOptions_reason(opts, &reason))
            })
        };
        match relay_while_busy(to_app.clone(), ctx.clone(), AWAKE_LINGER, hold) {
            Ok(tx) => tx,
            Err(e) => {
                log::warn!("control channel: no App Nap guard ({e})");
                to_app
            }
        }
    }
    #[cfg(not(target_os = "macos"))]
    {
        let _ = ctx;
        to_app
    }
}

/// See [`awake_while_busy`].
#[cfg_attr(not(target_os = "macos"), allow(dead_code))]
const AWAKE_LINGER: Duration = Duration::from_secs(2);

/// Forward control requests to `to_app`, holding a guard from `hold` while any are in flight (from
/// arrival until their reply, or until the app drops them) and for `linger` after the last one.
/// The guard is made and dropped on one thread of its own (Cocoa objects aren't `Send`).
#[cfg_attr(not(target_os = "macos"), allow(dead_code))]
fn relay_while_busy<G>(
    to_app: Sender<ControlRequest>,
    ctx: egui::Context,
    linger: Duration,
    hold: impl Fn() -> Option<G> + Send + 'static,
) -> std::io::Result<Sender<ControlRequest>> {
    let (busy_tx, busy_rx) = std::sync::mpsc::channel::<bool>();
    std::thread::Builder::new().name("ec-control-awake".into()).spawn(move || {
        let mut in_flight = 0usize;
        let mut guard = None;
        loop {
            let started = if in_flight == 0 && guard.is_some() {
                match busy_rx.recv_timeout(linger) {
                    Ok(started) => started,
                    Err(RecvTimeoutError::Timeout) => {
                        guard = None;
                        continue;
                    }
                    Err(RecvTimeoutError::Disconnected) => return,
                }
            } else {
                match busy_rx.recv() {
                    Ok(started) => started,
                    Err(_) => return,
                }
            };
            in_flight = if started { in_flight.saturating_add(1) } else { in_flight.saturating_sub(1) };
            if in_flight > 0 && guard.is_none() {
                guard = hold();
            }
        }
    })?;
    let (tx, rx) = std::sync::mpsc::channel::<ControlRequest>();
    std::thread::Builder::new().name("ec-control-relay".into()).spawn(move || {
        for mut req in rx {
            let _ = busy_tx.send(true);
            // The reply passes through a thread that marks the request done. If that thread
            // can't start, the request keeps its own reply channel.
            let (reply_tx, reply_rx) = std::sync::mpsc::channel();
            let reply = req.reply.clone();
            let done = busy_tx.clone();
            let waiter = std::thread::Builder::new().name("ec-control-reply".into()).spawn(move || {
                if let Ok(v) = reply_rx.recv() {
                    let _ = reply.send(v);
                }
                let _ = done.send(false);
            });
            match waiter {
                Ok(_) => req.reply = reply_tx,
                Err(_) => {
                    let _ = busy_tx.send(false);
                }
            }
            if to_app.send(req).is_err() {
                return;
            }
            // The server's repaint may have come before this request reached the app.
            ctx.request_repaint();
        }
    })?;
    Ok(tx)
}

