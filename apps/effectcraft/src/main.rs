    /// The App Nap guard is held from a control request's arrival until its reply (or until the
    /// app drops it), plus the linger, and only once for overlapping requests.
    #[test]
    fn control_requests_hold_the_awake_guard_while_in_flight() {
        use effectcraft_ui_egui::ControlRequest;
        use std::sync::Arc;
        use std::sync::atomic::{AtomicUsize, Ordering};
        use std::time::{Duration, Instant};
        struct Guard(Arc<AtomicUsize>);
        impl Drop for Guard {
            fn drop(&mut self) {
                self.0.fetch_sub(1, Ordering::SeqCst);
            }
        }
        let held = Arc::new(AtomicUsize::new(0));
        let begun = Arc::new(AtomicUsize::new(0));
        let (h, b) = (held.clone(), begun.clone());
        let (to_app, app) = std::sync::mpsc::channel();
        let linger = Duration::from_millis(100);
        let tx = super::relay_while_busy(to_app, egui::Context::default(), linger, move || {
            h.fetch_add(1, Ordering::SeqCst);
            b.fetch_add(1, Ordering::SeqCst);
            Some(Guard(h.clone()))
        })
        .unwrap();
        let wait_for = |what: &str, f: &dyn Fn() -> bool| {
            let t0 = Instant::now();
            while !f() {
                assert!(t0.elapsed() < Duration::from_secs(5), "{what}");
                std::thread::sleep(Duration::from_millis(5));
            }
        };
        let (a, a_reply) = ControlRequest::new("app.ping", serde_json::Value::Null);
        let (c, _c_reply) = ControlRequest::new("app.ping", serde_json::Value::Null);
        tx.send(a).unwrap();
        tx.send(c).unwrap();
        let a = app.recv_timeout(Duration::from_secs(5)).unwrap();
        let c = app.recv_timeout(Duration::from_secs(5)).unwrap();
        wait_for("held while in flight", &|| held.load(Ordering::SeqCst) == 1);
        a.reply.send(serde_json::json!({"ok": true})).unwrap();
        assert_eq!(a_reply.recv_timeout(Duration::from_secs(5)).unwrap(), serde_json::json!({"ok": true}));
        std::thread::sleep(linger * 2);
        assert_eq!(held.load(Ordering::SeqCst), 1, "the other request is still in flight");
        // A request the app drops unanswered is done too; the guard goes after the linger.
        drop(c);
        wait_for("released after the linger", &|| held.load(Ordering::SeqCst) == 0);
        assert_eq!(begun.load(Ordering::SeqCst), 1, "one guard for overlapping requests");
        // The next request takes it again.
        let (d, _d_reply) = ControlRequest::new("app.ping", serde_json::Value::Null);
        tx.send(d).unwrap();
        let _d = app.recv_timeout(Duration::from_secs(5)).unwrap();
        wait_for("held again", &|| held.load(Ordering::SeqCst) == 1);
    }

